const LANGS = { en: 'English', pt: 'Português' };
let LANG = (navigator.language || 'en').toLowerCase().startsWith('pt') ? 'pt' : 'en';

/** Translate a key. Extra arguments are passed to function values. */
function t(key, ...args) {
  const v = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(...args) : v;
}

/** Fill every [data-i18n*] attribute in the static HTML. Text only: never HTML. */
function applyI18n(root = document) {
  document.documentElement.lang = LANG === 'pt' ? 'pt-BR' : 'en';
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
